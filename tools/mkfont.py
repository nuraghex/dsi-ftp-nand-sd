#!/usr/bin/env python3
"""Generates source/font_data.c, the 8x8 glyphs used by the interface.

Sources (not executed, only read):
  * unscii-8 (public domain, https://github.com/viznut/unscii):
    Latin, Greek, Cyrillic, punctuation and symbols.
  * Fusion Pixel Font 8px proportional, BDF release
    (SIL OFL 1.1, https://github.com/TakWolf/fusion-pixel-font):
    kana and CJK ideographs. The Japanese variant is the main table; the
    Simplified Chinese glyphs that are drawn differently go into a second
    table used when the interface is in Chinese.

Usage:
  tools/mkfont.py <unscii-8.hex> <fusion-pixel-8px-proportional-ja.bdf>
                  <fusion-pixel-8px-proportional-zh_hans.bdf> <out.c>

Every glyph is 8x8, one byte per row, most significant bit on the left.
"""
import sys

# Ranges taken from unscii-8
UNSCII_RANGES = [
    (0x0020, 0x007E),  # ASCII
    (0x00A0, 0x024F),  # Latin-1 Supplement, Latin Extended-A/B
    (0x0370, 0x03FF),  # Greek
    (0x0400, 0x04FF),  # Cyrillic
    (0x2010, 0x205E),  # General punctuation
    (0x20A0, 0x20BF),  # Currency symbols
    (0x2190, 0x21FF),  # Arrows
    (0x2500, 0x25FF),  # Box drawing, block elements, geometric shapes
    (0x2713, 0x2717),  # Check marks
]

# Ranges taken from Fusion Pixel (8x8 cell, baseline under row 6)
CJK_RANGES = [
    (0x3000, 0x30FF),  # CJK punctuation, hiragana, katakana
    (0x31F0, 0x31FF),  # Katakana phonetic extensions
    (0x4E00, 0x9FFF),  # CJK unified ideographs
    (0xFF00, 0xFFEF),  # Halfwidth and fullwidth forms
]


def in_ranges(cp, ranges):
    return any(lo <= cp <= hi for lo, hi in ranges)


def load_unscii(path):
    glyphs = {}
    with open(path, encoding="ascii") as f:
        for line in f:
            line = line.strip()
            if ":" not in line:
                continue
            cp_hex, bits = line.split(":")
            cp = int(cp_hex, 16)
            if len(bits) == 16 and in_ranges(cp, UNSCII_RANGES):
                glyphs[cp] = bytes(int(bits[i:i + 2], 16) for i in range(0, 16, 2))
    return glyphs


def load_bdf_cells(path, ranges):
    """Glyphs of a BDF font placed in an 8x8 cell (baseline under row 6)."""
    glyphs = {}
    cropped = 0
    cur = None
    in_bitmap = False
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if line.startswith("STARTCHAR"):
                cur = {"rows": []}
            elif cur is None:
                continue
            elif line.startswith("ENCODING"):
                cur["cp"] = int(line.split()[1])
            elif line.startswith("BBX"):
                cur["bbx"] = tuple(map(int, line.split()[1:5]))
            elif line == "BITMAP":
                in_bitmap = True
            elif line == "ENDCHAR":
                in_bitmap = False
                cp = cur.get("cp", -1)
                if cp >= 0 and in_ranges(cp, ranges):
                    w, h, xo, yo = cur["bbx"]
                    nbytes = (w + 7) // 8
                    cell = [0] * 8
                    top = 7 - (yo + h)
                    if w + xo > 8 or top < 0 or top + h > 8:
                        cropped += 1
                    for r, v in enumerate(cur["rows"]):
                        y = top + r
                        if 0 <= y < 8:
                            row = v >> (nbytes * 8 - 8) if nbytes > 1 else v
                            cell[y] = (row >> xo) & 0xFF
                    if any(cell) or cp in (0x3000,):  # keep the ideographic space
                        glyphs[cp] = bytes(cell)
                cur = None
            elif in_bitmap:
                cur["rows"].append(int(line, 16))
    return glyphs, cropped


def c_table(name_cp, name_px, glyphs):
    cps = sorted(glyphs)
    out = [f"const u16 {name_cp}[] = {{"]
    for i in range(0, len(cps), 12):
        out.append("    " + ", ".join(f"0x{cp:04X}" for cp in cps[i:i + 12]) + ",")
    out.append("};")
    out.append(f"const u8 {name_px}[][8] = {{")
    for cp in cps:
        out.append("    {" + ",".join(f"0x{b:02X}" for b in glyphs[cp]) + "},")
    out.append("};")
    return out, len(cps)


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    unscii_path, ja_path, zh_path, out_path = sys.argv[1:]

    main_glyphs = load_unscii(unscii_path)
    ja, crop_ja = load_bdf_cells(ja_path, CJK_RANGES)
    zh, crop_zh = load_bdf_cells(zh_path, CJK_RANGES)

    zh_override = {}
    for cp, px in ja.items():
        main_glyphs[cp] = px
    for cp, px in zh.items():
        if cp not in ja:
            main_glyphs[cp] = px      # only in the Chinese variant
        elif px != ja[cp]:
            zh_override[cp] = px      # same character, Chinese shape

    lines = [
        "// Generated by tools/mkfont.py: do not edit, run the tool again.",
        "//",
        "// 8x8 glyphs, one byte per row, most significant bit on the left.",
        "// Latin, Greek, Cyrillic, symbols: unscii-8 by viznut (public domain).",
        "// Kana and CJK: Fusion Pixel Font 8px by TakWolf and contributors",
        "// (SIL Open Font License 1.1, see THIRD_PARTY_NOTICES.md).",
        "",
        '#include "font.h"',
        "",
    ]
    t, n_main = c_table("font_cp", "font_px", main_glyphs)
    lines += t + [""]
    t, n_zh = c_table("font_zh_cp", "font_zh_px", zh_override)
    lines += t + [""]
    lines.append(f"const int font_count = {n_main};")
    lines.append(f"const int font_zh_count = {n_zh};")
    with open(out_path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{out_path}: {n_main} glyphs, {n_zh} Chinese variants, "
          f"cropped ja={crop_ja} zh={crop_zh}, data {(n_main + n_zh) * 10 // 1024} KB")


if __name__ == "__main__":
    main()
